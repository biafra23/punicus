allprojects {
    group = "eth.serotine"
    version = "0.4.0-SNAPSHOT"

    // === Pinned dependency graph (#281) ==============================
    // Every resolvable configuration of every project is LOCKED: the exact
    // module versions it resolved to are committed in the project's
    // gradle.lockfile, so a transitive version range (or a publisher adding a
    // newer version inside one) cannot move what a tag builds. The bytes of each
    // of those modules are pinned separately, by SHA-256, in
    // gradle/verification-metadata.xml. Both are regenerated by ONE command,
    // scripts/update_gradle_pins.sh — see docs/gradle-dependency-pins.md.
    dependencyLocking {
        lockAllConfigurations()
        // Modules whose COORDINATES depend on the build host. Compose's
        // `compose.desktop.currentOs` is a different module per OS/arch
        // (desktop-jvm-macos-arm64, …-linux-x64, …-windows-x64), and with it
        // skiko's runtime. A lock written on Linux would refuse every macOS and
        // Windows build, so these stay out of the lock state. Their versions are
        // still fixed (they follow the pinned Compose version) and their bytes
        // are still pinned per host in verification-metadata.xml. (Kotlin/
        // Native's compiler bundle needs no entry: it is ONE module,
        // kotlin-native-prebuilt, locked like any other — the host is only in
        // its artifact's classifier, which the verification metadata pins.)
        ignoredDependencies.addAll(
            listOf(
                "org.jetbrains.compose.desktop:desktop-jvm-*",
                "org.jetbrains.skiko:skiko-awt-runtime-*",
                // Two modules whose presence in :android-app's runtime classpaths flips
                // between the run that writes the locks and every run after it, which has
                // the locks in force (Gradle 8.14 with AGP 8.13's compile/runtime classpath
                // alignment; seen in the first `gradle pins` runs of #281): the lock pass
                // records kotlin-stdlib-common, which a locked run then no longer selects,
                // and misses libsodium-bindings' resource-loader (excluded on :data's edge
                // to it), which a locked run then selects. No lock state can be right for
                // both, so they stay out of it. Their versions are still fixed:
                // kotlin-stdlib-common is aligned to the pinned Kotlin version by
                // kotlin-stdlib's own constraints, and resource-loader is a fixed version
                // in libsodium-bindings' POM. Their bytes are still pinned in
                // verification-metadata.xml. Revisit on the AGP 9 / Gradle 9 move.
                "org.jetbrains.kotlin:kotlin-stdlib-common",
                "com.goterl:resource-loader",
            ),
        )
        // DEFAULT lock mode, not STRICT: STRICT fails any configuration without
        // lock state, which would break an IDE sync (KGP's IDE-only
        // *DependenciesMetadata configurations never resolve in a build, so they
        // have none). resolveAllDependencies enforces STRICT's rule instead,
        // in the `gradle pins` check: a configuration that resolves without lock
        // state is a pin failure there.
    }

    // Resolves every resolvable configuration of this project (and of its
    // buildscript), so ONE invocation sees the whole graph — what
    // `--write-locks` and `--write-verification-metadata` need to write complete
    // pins. A plain build resolves only what its tasks happen to need, so pins
    // written from one would miss e.g. the test or lint classpaths and the next
    // build that needs them would fail verification. Configurations that cannot
    // resolve in a walk by design (KGP's commonizer inputs <sourceSet>CInterop,
    // which match no external variant; its IDE-only *DependenciesMetadata; the
    // Android ones without an SDK) are reported and skipped, not fatal. A PIN failure — an artifact whose hash is missing
    // or wrong, a graph that left its lock state — always fails the task: that
    // is the check the `gradle pins` workflow runs on every CI host.
    tasks.register("resolveAllDependencies") {
        group = "help"
        description = "Resolve every configuration (for scripts/update_gradle_pins.sh)."
        notCompatibleWithConfigurationCache("walks every configuration of the project")
        doLast {
            // Android lint (AGP's, on :android-app and the KMP modules' Android
            // targets) adds the dependencies of its lint configurations only
            // when its tasks are configured. Unrealized, those configurations hold nothing but
            // the lock's own constraints, and the walk reports every locked
            // module as "Did not resolve … part of the dependency lock state"
            // while a lint run resolves them all. Realizing the lint tasks first
            // gives the walk the graph lint resolves, so ONE lock state is right
            // for both. Only the lint tasks: realizing every task would configure
            // host-specific ones on all five pin hosts. (Ported from Myotis's
            // root build, its #734, where this walk was first proven.)
            project.tasks.names.filter { it.startsWith("lint") }.forEach { project.tasks.named(it).get() }
            val buildscriptConfs = project.buildscript.configurations.filter { it.isCanBeResolved }
            val confs = buildscriptConfs + project.configurations.filter { it.isCanBeResolved }
            // Lock state as committed: every configuration named in a lockfile
            // line (`group:name:version=confA,confB` or `empty=confC`). Only the
            // root's buildscript classpath is locked (see `buildscript {}`).
            fun lockedIn(file: File): Set<String> =
                if (!file.isFile) emptySet()
                else file.readLines()
                    .filter { it.isNotBlank() && !it.startsWith("#") }
                    .flatMap { it.substringAfter('=').split(',') }
                    .map { it.trim() }
                    .toSet()
            val projectLocks = lockedIn(project.file("gradle.lockfile"))
            val buildscriptLocks =
                if (project == rootProject) lockedIn(rootProject.file("buildscript-gradle.lockfile")) else null
            val writingLocks = gradle.startParameter.isWriteDependencyLocks
            // Every throwable under a failure: cause, suppressed, and the causes
            // of a multi-cause exception (by its public getCauses()). The
            // reflective call fails QUIETLY if a Gradle release drops the method,
            // leaving only the first cause, which hides a lock conflict again
            // (Gradle 9 puts it in a later cause). Only the `gradle pins` canary
            // notices, which is why it holds one case per pin-failure shape:
            // keep them all.
            fun everyThrowable(root: Throwable): List<Throwable> {
                val seen = mutableListOf<Throwable>()
                val queue = ArrayDeque(listOf(root))
                while (queue.isNotEmpty()) {
                    val t = queue.removeFirst()
                    if (seen.any { it === t }) continue
                    seen += t
                    t.cause?.let(queue::add)
                    queue.addAll(t.suppressed)
                    runCatching { t.javaClass.getMethod("getCauses").invoke(t) as? List<*> }
                        .getOrNull()?.filterIsInstance<Throwable>()?.let(queue::addAll)
                }
                return seen
            }
            fun isLockConflict(s: String) =
                "dependency was locked to version" in s ||
                    "dependency lock state" in s ||
                    ("version constraints" in s && "enforced by dependency locking" in s.lowercase())
            val pinFailures = mutableListOf<String>()
            confs.forEach { conf ->
                val locks = if (conf in buildscriptConfs) buildscriptLocks else projectLocks
                try {
                    // The graph (what the lock state records) …
                    conf.incoming.resolutionResult.root
                    // … and the files of every EXTERNAL module in it (what the
                    // verification metadata records). Project dependencies are
                    // filtered out: their artifacts are this build's own outputs,
                    // and selecting one needs the consumer-specific attributes
                    // (AGP's artifactType) a generic walk does not have.
                    conf.incoming.artifactView {
                        isLenient = false
                        componentFilter { it is org.gradle.api.artifacts.component.ModuleComponentIdentifier }
                    }.files.files
                    // A configuration that resolved must HAVE lock state (STRICT's
                    // rule, enforced here). Checked only now: the graph walk above
                    // does not throw on an unresolvable dependency, the file
                    // resolution does.
                    if (!writingLocks && locks != null && conf.name !in locks) {
                        pinFailures += "${project.path}:${conf.name} — resolves, but has no lock state"
                    }
                } catch (e: Exception) {
                    val chain = generateSequence<Throwable>(e) { it.cause }.toList()
                    // EVERY throwable under the failure, not only the `cause`
                    // chain: a resolution failure of several modules is a
                    // multi-cause exception (Gradle's internal MultiCauseException,
                    // reached by its public `getCauses()`), and since Gradle 9 the
                    // locking constraint's failure is a LATER cause — the first
                    // one is the bare "Could not resolve <the declared version>".
                    val all = everyThrowable(e)
                    // A wrong hash and an entry the lock lacks/has extra raise
                    // dedicated exceptions; a lock that pins a version the graph
                    // no longer accepts does NOT — it surfaces as an ordinary
                    // version-constraint conflict whose constraint names the lock:
                    // "dependency was locked to version" up to Gradle 8, "Dependency
                    // version enforced by Dependency Locking" from 9. It counts only
                    // inside a version-constraint conflict, the shape a stale lock
                    // version produces: every locked module carries the lock as a
                    // constraint, so a locked configuration that fails for another
                    // reason on this host (an unreachable repository, a variant
                    // this walk cannot select) can name it in its message tree too.
                    // The `gradle pins` canary fails if an upgrade words it a
                    // third way.
                    val lockFailure = all.firstOrNull { t ->
                        t.javaClass.simpleName.let {
                            it == "DependencyVerificationException" || it == "LockOutOfDateException"
                        } || isLockConflict(t.message.orEmpty())
                    }
                    val isPinFailure = lockFailure != null
                    val causes = listOfNotNull(
                        chain.mapNotNull { it.message }.joinToString(" <- "),
                        lockFailure?.takeIf { it !in chain }?.message,
                    ).joinToString(" <- ")
                    // Not a pin failure, but the GRAPH may still have resolved
                    // completely, and only the files could not be selected by this
                    // generic walk (attributes it lacks, a task output it would
                    // need). Such a configuration resolves in a real build, so
                    // STRICT's rule holds for it too: no lock state is a failure,
                    // not a skip. One whose graph did not resolve (an unresolvable
                    // dependency on this host) is skipped as before.
                    val graphResolved = runCatching {
                        conf.incoming.resolutionResult.allDependencies
                            .none { it is org.gradle.api.artifacts.result.UnresolvedDependencyResult }
                    }.getOrDefault(false)
                    if (isPinFailure) {
                        pinFailures += "${project.path}:${conf.name} — $causes"
                    } else if (graphResolved && !writingLocks && locks != null && conf.name !in locks) {
                        pinFailures += "${project.path}:${conf.name} — its graph resolves, but it has no lock state " +
                            "(its files could not be selected here: ${chain.firstOrNull()?.message.orEmpty().take(200)})"
                    } else {
                        // A skipped configuration WITH lock state is lock and hash
                        // state this host does not check; say so, so a tool bump
                        // that moves one into this branch shows in the log (the
                        // KGP *DependenciesMetadata ones are skipped by design).
                        val locked = locks != null && conf.name in locks
                        logger.warn(
                            "resolveAllDependencies: ${project.path}:${conf.name} skipped" +
                                (if (locked) " (has lock state, not checked here)" else "") + " — $causes",
                        )
                    }
                }
            }
            if (pinFailures.isNotEmpty()) {
                throw GradleException(
                    "Dependency pins do not match what this host resolves " +
                        "(run scripts/update_gradle_pins.sh; docs/gradle-dependency-pins.md):\n" +
                        pinFailures.joinToString("\n"),
                )
            }
        }
    }
}

// The release version — project.version minus the -SNAPSHOT suffix — and the
// BUILD NUMBER the installable apps derive from it, defined ONCE here and read
// by :android-app (versionCode) via rootProject.extra and by the iOS app's
// Xcode build via :printReleaseVersion (ios-app/xcode/project.yml), so a
// release sweep can never leave an app reporting the previous release.
//
// MAJOR*1_000_000 + MINOR*1_000 + PATCH is order-preserving for every semver
// bump (0.1.0 -> 1000, 0.2.0 -> 2000, 1.0.0 -> 1_000_000), so it is strictly
// increasing forever and — unlike a dotted "0.1.0" — a valid iOS
// CFBundleVersion for the day the iOS host arrives. It deliberately does NOT
// encode a -SNAPSHOT/-rc suffix: a re-cut of the same version gets the same
// number, so a re-cut bumps PATCH. MINOR/PATCH < 1000 keeps it under Android's
// 2_100_000_000 versionCode ceiling until MAJOR 2100.
val releaseVersion: String = project.version.toString().substringBefore('-')
val releaseBuildNumber: Int = releaseVersion.split('.').let { parts ->
    require(parts.size == 3 && parts.all { it.toIntOrNull() != null }) {
        "Unexpected project version '${project.version}': expected numeric MAJOR.MINOR.PATCH"
    }
    require(parts[1].toInt() < 1000 && parts[2].toInt() < 1000) {
        "MINOR/PATCH must stay below 1000 for the build-number mapping: ${project.version}"
    }
    parts[0].toInt() * 1_000_000 + parts[1].toInt() * 1_000 + parts[2].toInt()
}
extra["releaseVersion"] = releaseVersion
extra["releaseBuildNumber"] = releaseBuildNumber

// Release CI reads the version from HERE (via Gradle, so it can never drift from
// what the build actually uses) and refuses to publish when the pushed `v*` tag
// disagrees: otherwise tagging without bumping the version goes green and ships
// assets named after the tag while the binaries inside report the older version.
// This reads the ROOT project's version, which is what the apps see only because
// `allprojects` above sets ONE version for the whole build — give a module its
// own version and it silently stops being covered by the guard.
//
// Marker-prefixed output: `./gradlew -q` still lets non-task text reach stdout
// (wrapper distribution download progress on a cold runner, JVM/plugin warnings),
// so the consumer greps for the marker instead of trusting the last line.
//
// It also prints releaseBuildNumber=<n>, for the iOS app's Xcode build, which
// stamps both into the built Info.plist: Xcode reads its build settings before
// any script runs, so they cannot come from Gradle as settings, and a committed
// copy would be a second pin. The guard's pattern does not match that line.
tasks.register("printReleaseVersion") {
    group = "help"
    description = "Print the release version (project.version without -SNAPSHOT) as releaseVersion=<x.y.z>, " +
        "and the build number as releaseBuildNumber=<n>"
    // The task action captures plain values, so it stays configuration-cache
    // compatible.
    doLast {
        println("releaseVersion=$releaseVersion")
        println("releaseBuildNumber=$releaseBuildNumber")
    }
}

