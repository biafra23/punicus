#!/usr/bin/env python3
"""Writes the pinned Public Suffix List as Kotlin for :domain (docs/keys-and-signing.md, *Per-app addresses*).

    python3 scripts/public-suffix/generate.py

Reads scripts/public-suffix/public_suffix_list.dat, refuses it unless its sha256 is PINNED_SHA256, and writes
domain/src/commonMain/kotlin/eth/serotine/domain/model/PublicSuffixRules.kt. Every rule of both sections (ICANN and
private) is kept; a label outside ASCII is written in its `xn--` form (RFC 3492 Punycode), the form an AppHost holds.

The list is pinned: a per-app address hashes the registrable domain this list gives, so changing the list changes
addresses. Updating it is the owner's decision, never a routine refresh.
"""
import hashlib
import pathlib
import sys

PINNED_SHA256 = "c61dec506c4a1045355280a560bf66c9ee893fb1510db98510ef7fb277fb2df8"
FETCHED = "2026-11-15, https://raw.githubusercontent.com/publicsuffix/list/main/public_suffix_list.dat"
ROOT = pathlib.Path(__file__).resolve().parents[2]
SOURCE = ROOT / "scripts/public-suffix/public_suffix_list.dat"
TARGET = ROOT / "domain/src/commonMain/kotlin/eth/serotine/domain/model/PublicSuffixRules.kt"
CHUNK_BYTES = 60_000  # a JVM class file holds a string constant of at most 65535 bytes


def ascii_label(label: str) -> str:
    if label.isascii():
        return label
    return "xn--" + label.encode("punycode").decode("ascii")


def ascii_rule(rule: str) -> str:
    bang = rule.startswith("!")
    body = rule[1:] if bang else rule
    converted = ".".join(ascii_label(label) for label in body.lower().split("."))
    return ("!" if bang else "") + converted


def main() -> int:
    data = SOURCE.read_bytes()
    digest = hashlib.sha256(data).hexdigest()
    if digest != PINNED_SHA256:
        print(f"refused: {SOURCE} has sha256 {digest}, the pin is {PINNED_SHA256}", file=sys.stderr)
        return 1
    rules = []
    for line in data.decode("utf-8").splitlines():
        line = line.strip()
        if not line or line.startswith("//"):
            continue
        rules.append(ascii_rule(line.split()[0]))
    rules = sorted(set(rules))
    for rule in rules:
        body = rule.lstrip("!")
        assert body.isascii() and " " not in body and body == body.lower(), rule
    chunks, current = [], []
    size = 0
    for rule in rules:
        if size + len(rule) + 1 > CHUNK_BYTES:
            chunks.append("\n".join(current))
            current, size = [], 0
        current.append(rule)
        size += len(rule) + 1
    chunks.append("\n".join(current))
    out = [
        "// Generated by scripts/public-suffix/generate.py. Do not edit by hand.",
        f"// The Public Suffix List, sha256 {PINNED_SHA256},",
        f"// fetched {FETCHED}.",
        f"// {len(rules)} rules, both sections, every label in ASCII (`xn--` for the internationalised ones).",
        "// The list is subject to the Mozilla Public License, v. 2.0: https://mozilla.org/MPL/2.0/.",
        "// This file is derived from it and is under the same licence.",
        "package eth.serotine.domain.model",
        "",
        "/** The pinned list's sha256: docs/keys-and-signing.md names it beside the vectors. */",
        f'internal const val PUBLIC_SUFFIX_LIST_SHA256 = "{PINNED_SHA256}"',
        "",
        "/** The rules, one per line, in chunks a JVM string constant holds. */",
        "internal val PUBLIC_SUFFIX_RULES: List<String> = listOf(",
    ]
    for chunk in chunks:
        assert '"' not in chunk and "\\" not in chunk and "$" not in chunk
        out.append('    """' + chunk + '""",')
    out.append(")")
    TARGET.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{len(rules)} rules in {len(chunks)} chunks -> {TARGET.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
