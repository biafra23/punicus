// The Reown project IDs WalletConnect connects with (docs/walletconnect.md, ruling 2): never committed,
// passed as Gradle properties (from the CI secret or variable, or ~/.gradle/gradle.properties locally), one
// for debug builds and one for release builds (for now the same ID: owner ruling, 2026-11-05). A build
// without one has dApp connections switched off and says so. An ID is letters and digits: anything else
// fails the build rather than reach the code.
val generateWalletConnectBuildInfo by tasks.registering {
    val outDir = layout.buildDirectory.dir("generated/walletConnect/kotlin")
    // Trimmed: a secret pasted with a trailing newline or space is still the same ID.
    val debugId = providers.gradleProperty("walletConnectProjectIdDebug").map { it.trim() }.orElse("")
    val releaseId = providers.gradleProperty("walletConnectProjectIdRelease").map { it.trim() }.orElse("")
    inputs.property("debugId", debugId)
    inputs.property("releaseId", releaseId)
    outputs.dir(outDir)
    doLast {
        fun checked(name: String, value: String): String {
            require(value.all { it in 'a'..'z' || it in 'A'..'Z' || it in '0'..'9' }) {
                "$name must be letters and digits only"
            }
            return value
        }
        val debug = checked("walletConnectProjectIdDebug", debugId.get())
        val release = checked("walletConnectProjectIdRelease", releaseId.get())
        val f = outDir.get().file("eth/serotine/data/walletconnect/WalletConnectBuildInfo.kt").asFile
        f.parentFile.mkdirs()
        f.writeText(
            """
            // GENERATED by :data's generateWalletConnectBuildInfo task — do not edit.
            package eth.serotine.data.walletconnect

            /** The Reown project ID of debug builds, or empty when this build has none. */
            internal const val WALLETCONNECT_PROJECT_ID_DEBUG: String = "$debug"

            /** The Reown project ID of release builds, or empty when this build has none. */
            internal const val WALLETCONNECT_PROJECT_ID_RELEASE: String = "$release"
            """.trimIndent() + "\n",
        )
    }
}

